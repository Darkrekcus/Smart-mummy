/* ---------- 数量：辅食每道菜谱就是1个宝宝1餐份，不做人数缩放 ---------- */
function scaledQty(baseQty, _persons) {
  return Math.max(1, Number(baseQty) || 1);
}

/* ---------- 印尼语数量文本："2 potong labu" ---------- */
function formatQtyId(key, qty) {
  const ing = INGREDIENT_PRESETS.find(i => i.key === key);
  if (!ing) return qty + ' ' + key;
  return qty + ' ' + ing.unitId + ' ' + ing.nameId;
}

/* ---------- 渲染单步：把 {key} 换成数量文本 ---------- */
function renderStepId(recipe, step, persons) {
  return step.textId.replace(/\{(\w+)\}/g, (m, key) => {
    const found = recipe.ingredients.find(i => i.key === key);
    const base = found ? found.qty : 1;
    return formatQtyId(key, scaledQty(base, persons));
  });
}

/* ---------- 中文数量文本："2块南瓜" ---------- */
function formatQtyZh(key, qty) {
  const ing = INGREDIENT_PRESETS.find(i => i.key === key);
  if (!ing) return qty + '个' + key;
  return qty + ing.unitZh + ing.nameZh;
}

/* ---------- 渲染单步中文：同 renderStepId ---------- */
function renderStepZh(recipe, step, persons) {
  return step.textZh.replace(/\{(\w+)\}/g, (m, key) => {
    const found = recipe.ingredients.find(i => i.key === key);
    const base = found ? found.qty : 1;
    return formatQtyZh(key, scaledQty(base, persons));
  });
}

