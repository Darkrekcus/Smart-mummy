/* 中文名 → 预设 key（先匹配预设正式名，再匹配别名），没有则 null */
function presetKeyForZh(zh) {
  const p = INGREDIENT_PRESETS.find(x => x.nameZh === zh);
  if (p) return p.key;
  return ZH_ALIAS[zh] || null;
}

/* 自定义食材的图标：能对上预设/词典就用专属图标，否则默认 📦 */
function customEmoji(zh) {
  if (!zh) return '📦';
  const pk = presetKeyForZh(zh);
  if (pk) return INGREDIENT_PRESETS.find(x => x.key === pk).emoji;
  const d = ZH_TO_ID[zh];
  return d && d.emoji ? d.emoji : '📦';
}

